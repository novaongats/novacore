function calcMonthlyTaxR6(taxable, dependents) {
  const dep = Math.min(Math.max(Math.floor(Number(dependents) || 0), 0), 7);
  // 扶養7人超: 7人の税額から1人につき1,610円を控除（月額表甲欄の規定）
  const over7 = Math.max(0, Math.floor(Number(dependents) || 0) - 7);
  let tax = null;
  for (const row of MONTHLY_R6) {
    if (taxable <= row[0]) { tax = row[dep + 1]; break; }
  }
  if (tax === null) {
    const b = MONTHLY_R6_OVER[dep];
    tax = Math.floor((taxable - b.base) * b.rate) + b.tax;
  }
  return Math.max(0, tax - over7 * 1610);
}

