const R8_FROM = '2026-01';

/**
 * 月次給与の源泉所得税。
 * @param taxable    課税対象額 = 総支給 − 非課税通勤手当 − 社会保険料本人負担
 * @param dependents 扶養親族等（源泉控除対象親族）の数
 * @param month      'YYYY-MM'（省略時は令和8年方式）
 */
export function calcIncomeTaxForMonth(taxable, dependents, month) {
  const t = Math.max(0, Number(taxable) || 0);
  if (month && month < R8_FROM) return calcMonthlyTaxR6(t, dependents);
  return calcMonthlyTaxR8(t, dependents);
}

/**
 * 賞与に乗ずべき率（小数）。
 * @param prevAfterSocial 前月の社会保険料等控除後の給与等の金額
 */
export function getBonusTaxRateForMonth(prevAfterSocial, dependents, month) {
  if (month && month < R8_FROM) return bonusRateLegacy(prevAfterSocial, dependents);
  return bonusRateR8(prevAfterSocial, dependents);
}

