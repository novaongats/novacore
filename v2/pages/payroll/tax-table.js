// 月次: 令和8年分 電算機計算の特例（2026-01〜 適用）
// 財務省告示。控除月割額は1円未満切上げ、税額は10円未満四捨五入。
// ============================================================

function calcMonthlyTaxR8(taxable, dependents) {
  const A = Math.max(0, Math.floor(taxable)); // 社会保険料等控除後の給与等の金額
  const dep = Math.max(0, Math.floor(Number(dependents) || 0));

  // 別表第一: 給与所得控除の月割額（1円未満切上げ）
  let kyuyoKojo;
  if      (A <= 158333) kyuyoKojo = 54167;
  else if (A <= 299999) kyuyoKojo = Math.ceil(A * 0.30 +  6667);
  else if (A <= 549999) kyuyoKojo = Math.ceil(A * 0.20 + 36667);
  else if (A <= 708330) kyuyoKojo = Math.ceil(A * 0.10 + 91667);
  else                  kyuyoKojo = 162500;

  // 別表第二: 扶養親族等（源泉控除対象親族）1人につき 31,667円
  const fuyoKojo = dep * 31667;

  // 別表第三: 基礎控除の月割額（社保控除後給与の金額に応じて逓減）
  let kisoKojo;
  if      (A <= 2120833) kisoKojo = 48334;
  else if (A <= 2162499) kisoKojo = 40000;
  else if (A <= 2204166) kisoKojo = 26667;
  else if (A <= 2245833) kisoKojo = 13334;
  else                   kisoKojo = 0;

  // 課税給与所得金額
  const B = Math.max(0, A - kyuyoKojo - fuyoKojo - kisoKojo);
  if (B <= 0) return 0;

  // 別表第四: 税額の算式（復興特別所得税込み 102.1%）
  let tax;
  if      (B <=  162500) tax = B * 0.05105;
  else if (B <=  275000) tax = B * 0.10210 -   8296;
  else if (B <=  579166) tax = B * 0.20420 -  36374;
  else if (B <=  750000) tax = B * 0.23483 -  54113;
  else if (B <= 1500000) tax = B * 0.33693 - 130688;
  else if (B <= 3333333) tax = B * 0.40840 - 237893;
  else                   tax = B * 0.45945 - 408061;

  // 10円未満四捨五入
  return Math.max(0, Math.round(tax / 10) * 10);
}

